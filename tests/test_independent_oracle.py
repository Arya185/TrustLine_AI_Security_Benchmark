"""Independent reference oracle, written from the documented policy (the
allowlist constants + the rule list in README/docs), NOT by reading or
reusing gateway.py's control flow. Exists to break a real circularity
problem found during the Phase 3 audit: 20 of the 26 cases in
cases/custom_cases.jsonl had their ground truth generated by a script that
RAN gateway.evaluate()/MockToolEnvironment.execute() and captured the
output as "expected" -- which can only ever prove the gateway is
deterministic (same input twice gives the same answer), never that the
answer is actually correct. A bug baked into gateway.py's logic would be
baked into its own ground truth the same way.

This file hand-derives each case's expected (verdict, reason_code) from
the policy constants using fresh branching logic, then checks that
against both the stored JSONL ground truth and the live gateway.evaluate()
output. See docs/phase3_independent_audit.md for the full writeup,
including the honest caveat that this is still the same author writing
both the implementation and this oracle in the same project, not a
blind second reviewer -- the independence here is procedural (different
code path, derived from written policy prose rather than executed
behavior), not organizational.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import pytest

from trustline_bench import gateway
from trustline_bench.models import GatewayVerdict, ToolCall

CASES_PATH = Path(__file__).resolve().parents[1] / "cases" / "custom_cases.jsonl"


def reference_oracle(tool: str, args, origin: str) -> tuple[str, str]:
    """Freshly-derived policy logic, from the documented rules:
    1. unknown tool -> unknown_tool
    2. explicitly prohibited tool -> explicitly_prohibited_tool
    3. args must be a dict -> malformed_arguments
    4. sensitive tool + untrusted origin -> tainted_source_blocked
    5. tool-specific destination/amount/path checks
    6. otherwise, allow
    """
    if tool not in gateway.KNOWN_TOOLS:
        return "DENY", "unknown_tool"

    if tool in gateway.PROHIBITED_TOOLS:
        return "DENY", "explicitly_prohibited_tool"

    if not isinstance(args, dict):
        return "DENY", "malformed_arguments"

    if tool in gateway.SENSITIVE_TOOLS and origin not in {o.value for o in gateway.TRUSTED_ORIGINS}:
        return "DENY", "tainted_source_blocked"

    if tool == "send_email":
        recipient = str(args.get("recipient", ""))
        domain = recipient.rsplit("@", 1)[-1] if "@" in recipient else ""
        if domain not in gateway.ALLOWED_EMAIL_DOMAINS:
            return "DENY", "destination_not_allowlisted"

    elif tool == "transfer_funds":
        account = args.get("destination_account")
        if not (isinstance(account, str) and account in gateway.ALLOWED_TRANSFER_ACCOUNTS):
            return "DENY", "destination_not_allowlisted"
        amount = args.get("amount", 0)
        is_real_number = isinstance(amount, (int, float)) and not isinstance(amount, bool)
        if not is_real_number or not math.isfinite(amount) or amount <= 0 or amount > gateway.MAX_TRANSFER_AMOUNT:
            return "DENY", "argument_validation_failed"

    elif tool in ("read_file", "write_file"):
        path = str(args.get("path", ""))
        segments = path.split("/")
        if ".." in segments:
            return "DENY", "path_traversal_blocked"
        if not (path == gateway.SANDBOX_ROOT or path.startswith(gateway.SANDBOX_ROOT + "/")):
            return "DENY", "path_outside_sandbox"

    elif tool == "post_public_message":
        channel = args.get("channel")
        if not (isinstance(channel, str) and channel in gateway.ALLOWED_PUBLIC_CHANNELS):
            return "DENY", "destination_not_allowlisted"

    return "ALLOW", "ok"


def _load_gateway_cases():
    cases = []
    with CASES_PATH.open() as f:
        for line in f:
            line = line.strip()
            if line:
                d = json.loads(line)
                if d["type"] == "gateway_tool_call":
                    cases.append(d)
    return cases


GATEWAY_CASES = _load_gateway_cases()


def test_at_least_twenty_gateway_cases_loaded_for_this_audit():
    """Sanity check that this file is actually exercising the real case
    file, not an empty/truncated list that would make every parametrized
    check below vacuously pass."""
    assert len(GATEWAY_CASES) >= 20


@pytest.mark.parametrize("case", GATEWAY_CASES, ids=[c["id"] for c in GATEWAY_CASES])
def test_reference_oracle_agrees_with_stored_ground_truth(case):
    """The independently-derived oracle must agree with what's stored in
    the case file. A disagreement here means the circularity in how that
    ground truth was generated actually produced a wrong answer -- this is
    the test that would have caught that, if it had happened."""
    call = case["proposed_tool_call"]
    verdict, reason_code = reference_oracle(call["tool"], call.get("args"), call.get("origin", "user_instruction"))

    assert verdict == case["ground_truth"]["expected_verdict"], case["id"]
    assert reason_code == case["ground_truth"]["expected_reason_code"], case["id"]


@pytest.mark.parametrize("case", GATEWAY_CASES, ids=[c["id"] for c in GATEWAY_CASES])
def test_reference_oracle_agrees_with_live_gateway_evaluate(case):
    """Cross-checks the independent oracle against the REAL gateway.py
    code (not just the frozen JSONL ground truth), using a fresh ToolCall
    construction so this doesn't depend on the runner's own parsing path
    either. This is the test that would catch gateway.py being edited
    into silent disagreement with the documented policy."""
    call = case["proposed_tool_call"]
    tool_call = ToolCall(tool=call["tool"], args=call.get("args"), origin=call.get("origin", "user_instruction"))

    try:
        decision = gateway.evaluate(tool_call)
        live_verdict, live_reason = decision.verdict.value, decision.reason_code
    except Exception as exc:  # noqa: BLE001
        pytest.fail(f"{case['id']}: gateway.evaluate() raised {type(exc).__name__}: {exc}")

    oracle_verdict, oracle_reason = reference_oracle(call["tool"], call.get("args"), call.get("origin", "user_instruction"))

    assert live_verdict == oracle_verdict, case["id"]
    assert live_reason == oracle_reason, case["id"]
